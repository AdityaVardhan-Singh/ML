import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

from sklearn.preprocessing import StandardScaler
from sklearn.cluster import KMeans, AgglomerativeClustering
from scipy.cluster.hierarchy import linkage, dendrogram

df = pd.read_csv('/content/Mall_Customers (1).csv')

print("Dataset loaded successfully.")
print("Shape:", df.shape)

df.head()

print("Column names:")
print(df.columns.tolist())

print("\nDataset information:")
df.info()

print("\nMissing values:")
print(df.isnull().sum())

print("\nStatistical summary:")
df.describe()

X = df[['Annual Income (k$)', 'Spending Score (1-100)']]

print("Selected features:", X.columns.tolist())
print("Feature matrix shape:", X.shape)

X.head()

scaler = StandardScaler()

X_scaled = scaler.fit_transform(X)

print("Scaled feature matrix shape:", X_scaled.shape)
print("\nFirst five standardized records:")
print(X_scaled[:5])

inertia = []

for k in range(1, 11):
    kmeans = KMeans(n_clusters=k, random_state=42, n_init=10)
    kmeans.fit(X_scaled)
    inertia.append(kmeans.inertia_)

plt.figure(figsize=(8, 5))
plt.plot(range(1, 11), inertia, marker='o')
plt.xlabel('Number of Clusters (K)')
plt.ylabel('Inertia')
plt.title('Elbow Method for Optimal K')
plt.xticks(range(1, 11))
plt.grid(True)
plt.show()

kmeans = KMeans(n_clusters=5, random_state=42, n_init=10)
kmeans_labels = kmeans.fit_predict(X_scaled)

# Add cluster assignments to the original dataset
df['KMeans_Cluster'] = kmeans_labels

# Plot clusters using the original feature values
plt.figure(figsize=(9, 6))

plt.scatter(
    X['Annual Income (k$)'],
    X['Spending Score (1-100)'],
    c=kmeans_labels,
    cmap='viridis',
    s=60
)

# Convert standardized centroids back to original units
centroids = scaler.inverse_transform(kmeans.cluster_centers_)

plt.scatter(
    centroids[:, 0],
    centroids[:, 1],
    marker='X',
    s=250,
    c='red',
    label='Centroids'
)

plt.xlabel('Annual Income (k$)')
plt.ylabel('Spending Score (1-100)')
plt.title('Customer Segmentation using K-Means (K=5)')
plt.legend()
plt.show()

print("Customers in each cluster:")
print(df['KMeans_Cluster'].value_counts().sort_index())

# Create the hierarchical linkage matrix
Z = linkage(X_scaled, method='ward')

# Plot the dendrogram
plt.figure(figsize=(14, 6))

dendrogram(
    Z,
    truncate_mode='lastp',
    p=30,
    show_leaf_counts=True
)

plt.title('Hierarchical Clustering Dendrogram (Ward Linkage)')
plt.xlabel('Customer Groups')
plt.ylabel('Distance')
plt.show()

hierarchical = AgglomerativeClustering(
    n_clusters=5,
    linkage='ward'
)

hierarchical_labels = hierarchical.fit_predict(X_scaled)

df['Hierarchical_Cluster'] = hierarchical_labels

plt.figure(figsize=(9, 6))

plt.scatter(
    X['Annual Income (k$)'],
    X['Spending Score (1-100)'],
    c=hierarchical_labels,
    cmap='viridis',
    s=60
)

plt.xlabel('Annual Income (k$)')
plt.ylabel('Spending Score (1-100)')
plt.title('Customer Segmentation using Hierarchical Clustering (K=5)')
plt.show()

print("Customers in each hierarchical cluster:")
print(df['Hierarchical_Cluster'].value_counts().sort_index())