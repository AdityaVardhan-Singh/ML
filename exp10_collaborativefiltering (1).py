from surprise.model_selection import train_test_split
from surprise import accuracy

# 2. Load data (Surprise needs a specific format)
reader = Reader(rating_scale=(1, 5))
data = Dataset.load_from_df(ratings[['userId', 'movieId', 'rating']], reader)

# 3. Split into 80% train, 20% test (This is how real ML is evaluated)
trainset, testset = train_test_split(data, test_size=0.2, random_state=42)

# 4. Deploy SVD (Surprise handles all the NaNs and biases automatically!)
algo = SVD(n_factors=20, random_state=42)

# 5. Train the model
algo.fit(trainset)

# 6. Predict on the hidden 20% test set
predictions = algo.test(testset)

# 7. Evaluate using RMSE
rmse = accuracy.rmse(predictions)