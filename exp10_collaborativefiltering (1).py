import numpy as np
from sklearn.decomposition import TruncatedSVD
from sklearn.metrics import mean_squared_error

# 1. Create the matrix and get the global average rating
user_item_matrix = ratings.pivot(index='userId', columns='movieId', values='rating')
global_mean = ratings['rating'].mean()

# 2. Fill NaNs with the global mean (instead of 0)
# This prevents the algorithm from thinking unrated movies are rated 0.
matrix_filled = user_item_matrix.fillna(global_mean).values

# 3. Deploy SVD
svd = TruncatedSVD(n_components=20, random_state=42)
U = svd.fit_transform(matrix_filled)
Sigma = np.diag(svd.singular_values_)
Vt = svd.components_

# 4. Predict ratings
predicted_ratings = np.dot(np.dot(U, Sigma), Vt)

# 5. THE MAGIC FIX: Clip predictions to the valid 1-5 range
predicted_ratings = np.clip(predicted_ratings, 1.0, 5.0)

# 6. Evaluate using RMSE
actual_ratings = user_item_matrix.values
mask = ~np.isnan(actual_ratings) # Only look at real ratings

actual_values = actual_ratings[mask]
predicted_values = predicted_ratings[mask]

rmse = np.sqrt(mean_squared_error(actual_values, predicted_values))

print("==========================================")
print("FINAL EVALUATION FOR EXPERIMENT 10")
print("==========================================")
print(f"Root Mean Squared Error (RMSE): {rmse:.4f}")
print("==========================================")

